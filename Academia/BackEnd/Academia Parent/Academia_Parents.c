#include "Academia_Parents.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <winsqlite/winsqlite3.h>

static void write_js_escaped(FILE *out, const unsigned char *text) {
    if (text == NULL) return;
    for (int i = 0; text[i] != '\0'; i++) {
        if (text[i] == '\\' || text[i] == '"') {
            fputc('\\', out);
            fputc(text[i], out);
        } else if (text[i] == '\n') {
            fprintf(out, "\\n");
        } else if (text[i] == '\r') {
            /* skip */
        } else if (text[i] == '\t') {
            fprintf(out, "\\t");
        } else {
            fputc(text[i], out);
        }
    }
}

static void write_js_string(FILE *out, const unsigned char *text) {
    fprintf(out, "\"");
    write_js_escaped(out, text);
    fprintf(out, "\"");
}

void update_parent_frontend_state(int parent_user_id) {
    sqlite3 *db = NULL;
    sqlite3_stmt *stmt = NULL;
    FILE *out = NULL;
    int result = 0;

    if (sqlite3_open("academia.db", &db) != SQLITE_OK) {
        printf("[Parent Module] Cannot open academia.db\n");
        if (db) sqlite3_close(db);
        return;
    }

    out = fopen("FrontEnd/JS/parents_states.js", "w");
    if (out == NULL) {
        out = fopen("BackEnd/Academia Parent/parents_states.js", "w");
        if (out == NULL) {
            printf("[Parent Module] Cannot open parents_states.js for writing.\n");
            sqlite3_close(db);
            return;
        }
    }

    fprintf(out, "// Auto-generated by Academia C Backend with SQLite3\n");
    fprintf(out, "const parentState = {\n");

    /* 1. PARENT PROFILE */
    fprintf(out, "  parent: {\n");
    const char *sql_parent = 
        "SELECT user.id, user.username, user.first_name, user.last_name, parent.phone "
        "FROM user INNER JOIN parent ON user.id = parent.id "
        "WHERE user.id = ? AND user.role = 'parent';";

    int parent_found = 0;
    if (sqlite3_prepare_v2(db, sql_parent, -1, &stmt, NULL) == SQLITE_OK) {
        sqlite3_bind_int(stmt, 1, parent_user_id);
        if (sqlite3_step(stmt) == SQLITE_ROW) {
            parent_found = 1;
            fprintf(out, "    userId: %d,\n", sqlite3_column_int(stmt, 0));
            fprintf(out, "    username: "); write_js_string(out, sqlite3_column_text(stmt, 1)); fprintf(out, ",\n");
            fprintf(out, "    firstName: "); write_js_string(out, sqlite3_column_text(stmt, 2)); fprintf(out, ",\n");
            fprintf(out, "    lastName: "); write_js_string(out, sqlite3_column_text(stmt, 3)); fprintf(out, ",\n");
            fprintf(out, "    phone: "); write_js_string(out, sqlite3_column_text(stmt, 4)); fprintf(out, "\n");
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  },\n");

    /* 2. LINKED STUDENT */
    fprintf(out, "  student: {\n");
    const char *sql_child = 
        "SELECT user.id, user.first_name, user.last_name, student.grade_level, student.gpa "
        "FROM student "
        "JOIN user ON student.id = user.id "
        "WHERE student.parent_id = ?;";
    int child_id = 0;
    if (sqlite3_prepare_v2(db, sql_child, -1, &stmt, NULL) == SQLITE_OK) {
        sqlite3_bind_int(stmt, 1, parent_user_id);
        if (sqlite3_step(stmt) == SQLITE_ROW) {
            child_id = sqlite3_column_int(stmt, 0);
            fprintf(out, "    studentId: %d,\n", child_id);
            fprintf(out, "    firstName: "); write_js_string(out, sqlite3_column_text(stmt, 1)); fprintf(out, ",\n");
            fprintf(out, "    lastName: "); write_js_string(out, sqlite3_column_text(stmt, 2)); fprintf(out, ",\n");
            fprintf(out, "    gradeLevel: %d,\n", sqlite3_column_int(stmt, 3));
            fprintf(out, "    gpa: %.2f\n", sqlite3_column_double(stmt, 4));
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  },\n");

    /* 3. CHILD'S GRADES */
    fprintf(out, "  grades: [\n");
    if (child_id > 0) {
        const char *sql_grades = 
            "SELECT course.course_name, grade.score "
            "FROM grade JOIN course ON grade.course_id = course.id "
            "WHERE grade.student_id = ?;";
        if (sqlite3_prepare_v2(db, sql_grades, -1, &stmt, NULL) == SQLITE_OK) {
            sqlite3_bind_int(stmt, 1, child_id);
            while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
                fprintf(out, "    { course: "); write_js_string(out, sqlite3_column_text(stmt, 0));
                fprintf(out, ", score: %.1f },\n", sqlite3_column_double(stmt, 1));
            }
            sqlite3_finalize(stmt);
        }
    }
    fprintf(out, "  ],\n");

    /* 4. CHILD'S ATTENDANCE */
    fprintf(out, "  attendance: [\n");
    if (child_id > 0) {
        const char *sql_att = 
            "SELECT course.course_name, attendance.present "
            "FROM attendance JOIN course ON attendance.course_id = course.id "
            "WHERE attendance.student_id = ?;";
        if (sqlite3_prepare_v2(db, sql_att, -1, &stmt, NULL) == SQLITE_OK) {
            sqlite3_bind_int(stmt, 1, child_id);
            while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
                fprintf(out, "    { course: "); write_js_string(out, sqlite3_column_text(stmt, 0));
                fprintf(out, ", status: \"%s\" },\n", sqlite3_column_int(stmt, 1) ? "Present" : "Absent");
            }
            sqlite3_finalize(stmt);
        }
    }
    fprintf(out, "  ],\n");

    /* 5. ANNOUNCEMENTS */
    fprintf(out, "  announcements: [\n");
    const char *sql_ann = 
        "SELECT course.course_name, announcement.title, announcement.message, announcement.announcement_date "
        "FROM announcement "
        "LEFT JOIN course ON announcement.course_id = course.id "
        "ORDER BY announcement.id DESC;";
    if (sqlite3_prepare_v2(db, sql_ann, -1, &stmt, NULL) == SQLITE_OK) {
        while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
            fprintf(out, "    { course: "); write_js_string(out, sqlite3_column_text(stmt, 0) ? sqlite3_column_text(stmt, 0) : (const unsigned char*)"General");
            fprintf(out, ", title: "); write_js_string(out, sqlite3_column_text(stmt, 1));
            fprintf(out, ", message: "); write_js_string(out, sqlite3_column_text(stmt, 2));
            fprintf(out, ", date: "); write_js_string(out, sqlite3_column_text(stmt, 3));
            fprintf(out, " },\n");
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  ],\n");

    fprintf(out, "  success: %s\n", parent_found ? "true" : "false");
    fprintf(out, "};\n");

    fclose(out);
    sqlite3_close(db);
    printf("[Parent Module] Successfully updated parents_states.js for parent ID %d\n", parent_user_id);
}
