#include "Academia_Staff.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <winsqlite/winsqlite3.h>

static void write_js_escaped(FILE *out, const unsigned char *text) {
    if (text == NULL) return;
    for (int i = 0; text[i] != '\0'; i++) {
        if (text[i] == '\\' || text[i] == '"') {
            fputc('\\', out);
            fputc(text[i], out);
        } else if (text[i] == '\n') {
            fprintf(out, "\\n");
        } else if (text[i] == '\r') {
            /* skip */
        } else if (text[i] == '\t') {
            fprintf(out, "\\t");
        } else {
            fputc(text[i], out);
        }
    }
}

static void write_js_string(FILE *out, const unsigned char *text) {
    fprintf(out, "\"");
    write_js_escaped(out, text);
    fprintf(out, "\"");
}

void update_staff_frontend_state(int staff_user_id) {
    sqlite3 *db = NULL;
    sqlite3_stmt *stmt = NULL;
    FILE *out = NULL;
    int result = 0;

    if (sqlite3_open("academia.db", &db) != SQLITE_OK) {
        printf("[Staff Module] Cannot open academia.db\n");
        if (db) sqlite3_close(db);
        return;
    }

    out = fopen("FrontEnd/JS/staff_states.js", "w");
    if (out == NULL) {
        out = fopen("BackEnd/Academia Staff/staff_states.js", "w");
        if (out == NULL) {
            printf("[Staff Module] Cannot open staff_states.js for writing.\n");
            sqlite3_close(db);
            return;
        }
    }

    fprintf(out, "// Auto-generated by Academia C Backend with SQLite3\n");
    fprintf(out, "const staffState = {\n");

    /* 1. STAFF PROFILE */
    fprintf(out, "  staff: {\n");
    const char *sql_staff = 
        "SELECT user.id, user.username, user.first_name, user.last_name, staff.phone "
        "FROM user INNER JOIN staff ON user.id = staff.id "
        "WHERE user.id = ? AND user.role = 'staff';";

    int staff_found = 0;
    if (sqlite3_prepare_v2(db, sql_staff, -1, &stmt, NULL) == SQLITE_OK) {
        sqlite3_bind_int(stmt, 1, staff_user_id);
        if (sqlite3_step(stmt) == SQLITE_ROW) {
            staff_found = 1;
            fprintf(out, "    userId: %d,\n", sqlite3_column_int(stmt, 0));
            fprintf(out, "    username: "); write_js_string(out, sqlite3_column_text(stmt, 1)); fprintf(out, ",\n");
            fprintf(out, "    firstName: "); write_js_string(out, sqlite3_column_text(stmt, 2)); fprintf(out, ",\n");
            fprintf(out, "    lastName: "); write_js_string(out, sqlite3_column_text(stmt, 3)); fprintf(out, ",\n");
            fprintf(out, "    phone: "); write_js_string(out, sqlite3_column_text(stmt, 4)); fprintf(out, "\n");
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  },\n");

    /* 2. COURSES */
    fprintf(out, "  courses: [\n");
    const char *sql_courses = "SELECT id, course_name FROM course WHERE staff_id = ?;";
    if (sqlite3_prepare_v2(db, sql_courses, -1, &stmt, NULL) == SQLITE_OK) {
        sqlite3_bind_int(stmt, 1, staff_user_id);
        while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
            fprintf(out, "    { courseId: %d, course: ", sqlite3_column_int(stmt, 0));
            write_js_string(out, sqlite3_column_text(stmt, 1));
            fprintf(out, " },\n");
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  ],\n");

    /* 3. ENROLLED STUDENTS */
    fprintf(out, "  enrollments: [\n");
    const char *sql_enroll = 
        "SELECT DISTINCT user.id, user.first_name || ' ' || user.last_name, course.id, course.course_name "
        "FROM enrollment "
        "JOIN user ON enrollment.student_id = user.id "
        "JOIN course ON enrollment.course_id = course.id "
        "WHERE course.staff_id = ?;";
    if (sqlite3_prepare_v2(db, sql_enroll, -1, &stmt, NULL) == SQLITE_OK) {
        sqlite3_bind_int(stmt, 1, staff_user_id);
        while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
            fprintf(out, "    { studentId: %d, student: ", sqlite3_column_int(stmt, 0));
            write_js_string(out, sqlite3_column_text(stmt, 1));
            fprintf(out, ", courseId: %d, course: ", sqlite3_column_int(stmt, 2));
            write_js_string(out, sqlite3_column_text(stmt, 3));
            fprintf(out, " },\n");
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  ],\n");

    /* 4. GRADES */
    fprintf(out, "  grades: [\n");
    const char *sql_grades = 
        "SELECT grade.id, user.first_name || ' ' || user.last_name, course.course_name, grade.score "
        "FROM grade "
        "JOIN user ON grade.student_id = user.id "
        "JOIN course ON grade.course_id = course.id "
        "WHERE course.staff_id = ?;";
    if (sqlite3_prepare_v2(db, sql_grades, -1, &stmt, NULL) == SQLITE_OK) {
        sqlite3_bind_int(stmt, 1, staff_user_id);
        while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
            fprintf(out, "    { gradeId: %d, student: ", sqlite3_column_int(stmt, 0));
            write_js_string(out, sqlite3_column_text(stmt, 1));
            fprintf(out, ", course: "); write_js_string(out, sqlite3_column_text(stmt, 2));
            fprintf(out, ", score: %.1f },\n", sqlite3_column_double(stmt, 3));
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  ],\n");

    /* 5. ATTENDANCE */
    fprintf(out, "  attendance: [\n");
    const char *sql_att = 
        "SELECT attendance.id, user.first_name || ' ' || user.last_name, course.course_name, attendance.present "
        "FROM attendance "
        "JOIN user ON attendance.student_id = user.id "
        "JOIN course ON attendance.course_id = course.id "
        "WHERE course.staff_id = ?;";
    if (sqlite3_prepare_v2(db, sql_att, -1, &stmt, NULL) == SQLITE_OK) {
        sqlite3_bind_int(stmt, 1, staff_user_id);
        while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
            fprintf(out, "    { attendanceId: %d, student: ", sqlite3_column_int(stmt, 0));
            write_js_string(out, sqlite3_column_text(stmt, 1));
            fprintf(out, ", course: "); write_js_string(out, sqlite3_column_text(stmt, 2));
            fprintf(out, ", present: %d },\n", sqlite3_column_int(stmt, 3));
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  ],\n");

    /* 6. ANNOUNCEMENTS */
    fprintf(out, "  announcements: [\n");
    const char *sql_ann = 
        "SELECT announcement.id, course.course_name, announcement.title, announcement.message, announcement.announcement_date "
        "FROM announcement "
        "LEFT JOIN course ON announcement.course_id = course.id "
        "ORDER BY announcement.id DESC;";
    if (sqlite3_prepare_v2(db, sql_ann, -1, &stmt, NULL) == SQLITE_OK) {
        while ((result = sqlite3_step(stmt)) == SQLITE_ROW) {
            fprintf(out, "    { announcementId: %d, course: ", sqlite3_column_int(stmt, 0));
            write_js_string(out, sqlite3_column_text(stmt, 1) ? sqlite3_column_text(stmt, 1) : (const unsigned char*)"General");
            fprintf(out, ", title: "); write_js_string(out, sqlite3_column_text(stmt, 2));
            fprintf(out, ", message: "); write_js_string(out, sqlite3_column_text(stmt, 3));
            fprintf(out, ", date: "); write_js_string(out, sqlite3_column_text(stmt, 4));
            fprintf(out, " },\n");
        }
        sqlite3_finalize(stmt);
    }
    fprintf(out, "  ],\n");

    fprintf(out, "  success: %s\n", staff_found ? "true" : "false");
    fprintf(out, "};\n");

    fclose(out);
    sqlite3_close(db);
    printf("[Staff Module] Successfully updated staff_states.js for staff ID %d\n", staff_user_id);
}
