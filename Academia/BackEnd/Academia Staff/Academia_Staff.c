#include "Academia_Staff.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sqlite3.h>

void update_staff_frontend_state(int staff_user_id) {
    sqlite3 *db = NULL;
    if (sqlite3_open("academia.db", &db) != SQLITE_OK) return;

    FILE *out = fopen("FrontEnd/JS/staff_states.js", "w");
    if (!out) {
        sqlite3_close(db);
        return;
    }

    fprintf(out, "// Auto-generated by C Backend\nconst staffState = {\n  staffId: %d,\n  success: true\n};\n", staff_user_id);
    fclose(out);
    sqlite3_close(db);
}